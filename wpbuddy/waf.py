"""WAF awareness: fingerprinting, block detection and bypass accounting.

A WAF in front of a WordPress site silently eats scanner probes (Wordfence
famously 403s readme.txt probing, Cloudflare whole path classes). The scanner
needs to (a) know which WAF it is talking to, (b) recognize when a response
is a block rather than a real answer, and (c) remember which obfuscation
techniques got through, for the report.

Detection is passive: signatures are read from headers, cookies and block
pages of responses the scanner already makes. This module keeps no network
code of its own.
"""

import re

# name -> ({header-name: value-prefix/regex/None}, cookie-prefixes, body-regex-TUPLES)
SIGNATURES = {
    "Cloudflare": ({"server": "cloudflare", "cf-ray": None}, ("__cf_bm", "__cfduid", "cf_clearance"),
                   (re.compile(r"Attention Required!\s*\|\s*Cloudflare|cloudflare-nginx|cf-error", re.I),)),
    "Wordfence": ({}, ("wfvt_", "wordfence_"),
                  (re.compile(r"Generated by Wordfence|Your access to this service has been temporarily blocked", re.I),)),
    "Sucuri": ({"server": "sucuri", "x-sucuri-id": None}, (),
               (re.compile(r"sucuri/website firewall|Access Denied - Sucuri", re.I),)),
    "ModSecurity": ({"server": re.compile(r"mod[_-]?security", re.I)}, (),
                    (re.compile(r"ModSecurity|This error was generated by Mod_Security", re.I),)),
    "AWS WAF": ({"x-amzn-waf-action": None}, (),
                (re.compile(r"Request blocked\.|AWS WAF", re.I),)),
    "Imperva/Incapsula": ({"x-iinfo": None}, ("incap_ses", "visid_incap"),
                          (re.compile(r"Request unsuccessful\. Incapsula|Imperva", re.I),)),
    "LiteSpeed WAF": ({}, ("litespeed_cvisitor",),
                      (re.compile(r"LiteSpeed.*(?:blocked|firewall)|reached a rate limit", re.I),)),
}

# Statuses that mean "a firewall blocked THIS request" and justify retrying
# through an obfuscated path variant. 429 is deliberately absent: it is rate
# limiting, and httpclient answers it with a scan-wide cool-down - path tricks
# don't help and only add load.
BLOCK_STATUSES = {403, 406, 501}

_detected = set()
_blocked_responses = 0
_bypass_events = {}   # technique -> occurrences


def inspect_response(resp):
    """Called by httpclient for every response; keeps the fingerprint fresh."""
    if resp is None:
        return
    headers = {k.lower(): (v or "") for k, v in (getattr(resp, "headers", None) or {}).items()}
    cookies = " ".join(getattr(resp, "cookies", None).keys() if getattr(resp, "cookies", None) else [])
    body_head = (resp.text or "")[:4000]

    for name, (header_sigs, cookie_prefixes, body_res) in SIGNATURES.items():
        if name in _detected:
            continue
        for header, marker in header_sigs.items():
            value = headers.get(header)
            if value is None:
                continue
            if marker is None or (isinstance(marker, str) and value.lower().startswith(marker)) \
                    or (hasattr(marker, "search") and marker.search(value)):
                _detected.add(name)
                print(f"[*] WAF detected: {name} (via {header} header)")
                break
        if name in _detected:
            continue
        if any(c.startswith(p) for c in cookies.split() for p in cookie_prefixes):
            _detected.add(name)
            print(f"[*] WAF detected: {name} (via cookie)")
            continue
        if any(rx.search(body_head) for rx in body_res):
            _detected.add(name)
            print(f"[*] WAF detected: {name} (via block-page content)")


def is_blocked(resp):
    """True when the response looks like a firewall block, not a real answer."""
    if resp is None:
        return False
    return resp.status_code in BLOCK_STATUSES


def note_block():
    global _blocked_responses
    _blocked_responses += 1


def note_bypass(technique):
    _bypass_events[technique] = _bypass_events.get(technique, 0) + 1
    print(f"[*] WAF bypass: plain path was blocked, variant '{technique}' got through")


def detected():
    return sorted(_detected)


def bypass_events():
    return dict(_bypass_events)


def reset():
    """Clear state (between scans/tests)."""
    _detected.clear()
    _bypass_events.clear()
    global _blocked_responses
    _blocked_responses = 0


def write_report(report):
    if not _detected and not _bypass_events:
        return
    report.section("Web Application Firewall")
    if _detected:
        report.paragraph("A firewall layer was detected in front of the site: "
                         + ", ".join(f"**{n}**" for n in sorted(_detected))
                         + ". Expect some probes to be blocked or filtered; findings that "
                           "require reaching filtered paths may be underreported here.")
    if _bypass_events:
        report.paragraph("Path obfuscation techniques that got past the firewall during this "
                         "scan (each was used only after the plain request was blocked): "
                         + ", ".join(f"`{tech}` x{n}" for tech, n in sorted(_bypass_events.items())))
        report.paragraph("**Recommendation:** a WAF that can be sidestepped by simple path "
                         "normalization tricks provides detection, not prevention - tune its "
                         "rules and keep WordPress/components updated as the primary defense.")
